/** Deterministic daily prompt; `offset` lets the user shuffle. @param {string} dateKey @param {number} [offset] */
export function promptFor(dateKey, offset = 0) {
  let hash = 2166136261;
  for (const ch of dateKey) hash = Math.imul(hash ^ ch.charCodeAt(0), 16777619);
  return PROMPTS[((hash >>> 0) + offset) % PROMPTS.length];
}
